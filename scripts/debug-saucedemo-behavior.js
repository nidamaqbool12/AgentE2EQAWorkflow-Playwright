const { chromium } = require('@playwright/test');
(async () => {
  const browser = await chromium.launch();
  const page = await browser.newPage();
  await page.goto('https://www.saucedemo.com');
  await page.fill('[data-test="username"]', 'standard_user');
  await page.fill('[data-test="password"]', 'secret_sauce');
  await page.click('[data-test="login-button"]');
  await page.waitForURL(/.*inventory\.html/);
  const addButtons = await page.locator('[data-test^="add-to-cart-"]').all();
  console.log('add count', addButtons.length);
  await addButtons[0].click();
  await addButtons[1].click();
  await page.click('.shopping_cart_link');
  await page.waitForURL(/.*cart\.html/);
  await page.click('[data-test="checkout"]');
  await page.waitForURL('**/checkout-step-one.html');
  await page.fill('[data-test="firstName"]', 'Test');
  await page.fill('[data-test="lastName"]', 'User');
  await page.fill('[data-test="postalCode"]', '!@#$%');
  await page.click('[data-test="continue"]');
  const errorLocator = page.locator('[data-test="error"]');
  console.log('error count after invalid postal', await errorLocator.count());
  if (await errorLocator.count() > 0) console.log('error text:', await errorLocator.innerText());
  console.log('current url after invalid postal', page.url());
  await page.fill('[data-test="postalCode"]', '12345');
  await page.click('[data-test="continue"]');
  await page.waitForURL(/.*checkout-step-two\.html/);
  await page.click('[data-test="cancel"]');
  console.log('url after overview cancel immediate', page.url());
  await page.waitForTimeout(1000);
  console.log('url after overview cancel wait', page.url());
  await browser.close();
})();
